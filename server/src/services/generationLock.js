/**
 * Не даёт запустить генерацию одной и той же инструкции (один и тот же id)
 * дважды параллельно — неважно, откуда пришёл запрос: кнопка «сгенерировать»
 * в поиске, кнопка «+ сгенерировать инструкцию» в шапке или автогенерация
 * по расписанию. Без этого при пересечении по времени (например, админ
 * вручную генерирует профессию, которая в тот же момент подхватывается
 * очередью автогенерации) YandexGPT дёргался бы дважды на одну и ту же
 * профессию, а второй результат просто перезаписывал бы файл первого —
 * впустую потраченные запросы и шанс на два слегка разных текста поверх
 * друг друга. Теперь второй (и любой следующий) вызов для того же id
 * просто дожидается результата уже идущей генерации вместо того, чтобы
 * запускать свою.
 */

const inFlight = new Map(); // id -> Promise<instruction>

/** Есть ли прямо сейчас незавершённая генерация для этого id. */
export function isGenerationInFlight(id) {
  return inFlight.has(id);
}

/**
 * Выполняет task() эксклюзивно по ключу id: если для этого id уже идёт
 * генерация — возвращает тот же промис вместо повторного запуска.
 */
export function runExclusive(id, task) {
  const existing = inFlight.get(id);
  if (existing) {
    return existing;
  }

  const promise = Promise.resolve()
    .then(task)
    .finally(() => {
      inFlight.delete(id);
    });

  inFlight.set(id, promise);
  return promise;
}