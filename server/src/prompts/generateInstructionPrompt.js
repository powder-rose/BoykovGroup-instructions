/**
 * Промпт для запроса ОДНОГО раздела. Для первого раздела дополнительно
 * просим название документа и короткое введение — с чёткими текстовыми
 * маркерами, чтобы сервис мог надёжно разобрать ответ на части.
 */
function buildSectionUserPrompt(profession, sectionDef, { includeTitleAndIntro }) {
  const checklistText = sectionDef.checklist.join("\n");

  const sectionInstruction = `Напиши раздел ${sectionDef.number} — «${sectionDef.heading}» —
инструкции по охране труда для профессии «${profession}».

Этот раздел должен состоять СТРОГО из ${sectionDef.requiredCount} пунктов — не больше и не
меньше. Ниже — обязательный перечень того, что должен раскрывать каждый пункт (это чеклист
требований, а не готовый текст!). Разверни каждый пункт в подробный профессиональный текст
(не менее 200 символов), адаптированный под профессию «${profession}», не копируя формулировки
чеклиста дословно:

${checklistText}

Верни только текст раздела: подряд идущие пункты вида «${sectionDef.number}.1. текст», «${sectionDef.number}.2. текст»
и так далее, каждый с новой строки. Без заголовка раздела, без markdown, без списков-буллетов
внутри пунктов, без пояснений до или после текста.`;

  if (!includeTitleAndIntro) {
    return sectionInstruction;
  }

  return `Прежде чем писать раздел 1, сформулируй название документа и короткое введение.

Ответ должен состоять строго из трёх частей подряд, каждая со своей меткой на отдельной строке
(метки пиши ТОЧНО как показано, они нужны для автоматической обработки ответа):

### НАЗВАНИЕ ###
(название инструкции с корректным склонением профессии в родительном падеже, например:
«Инструкция по охране труда для ${profession}» — но со склонением; без кавычек в самом названии)

### ВВЕДЕНИЕ ###
(2-3 предложения общего профессионального введения об инструкции для профессии «${profession}»,
сплошным текстом, без нумерации)

### РАЗДЕЛ ###
${sectionInstruction}`;
}

