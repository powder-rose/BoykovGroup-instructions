/**
 * ЗАГЛУШКА ПРОМПТА для YandexGPT.
 * Пользователь пришлёт финальный текст промпта позже — тогда нужно будет
 * заменить только содержимое функции buildGenerateInstructionPrompt ниже,
 * не трогая остальной код (yandexGptService.js и роуты его не знают
 * и работают с любым текстом промпта).
 *
 * Требования к результату модели заданы прямо в промпте: строгий JSON,
 * повторяющий структуру эталонной инструкции по охране труда
 * (см. server/src/data/instructions/apparatchik-okisleniya.json) —
 * 5 фиксированных разделов, пронумерованные пункты вида "N.M. ...".
 */

const SECTION_TEMPLATE = [
  { number: 1, heading: "ОБЩИЕ ТРЕБОВАНИЯ ОХРАНЫ ТРУДА" },
  { number: 2, heading: "ТРЕБОВАНИЯ ОХРАНЫ ТРУДА ПЕРЕД НАЧАЛОМ РАБОТЫ" },
  { number: 3, heading: "ТРЕБОВАНИЯ ОХРАНЫ ТРУДА ВО ВРЕМЯ РАБОТЫ" },
  { number: 4, heading: "ТРЕБОВАНИЯ ОХРАНЫ ТРУДА В АВАРИЙНЫХ СИТУАЦИЯХ" },
  { number: 5, heading: "ТРЕБОВАНИЯ ОХРАНЫ ТРУДА ПО ОКОНЧАНИИ РАБОТЫ" },
];

/**
 * @param {string} profession - профессия/название инструкции, которую ввёл
 *   пользователь в поиске (например: "аппаратчик сушки", "оператор котельной").
 * @returns {{ system: string, user: string }}
 */
export function buildGenerateInstructionPrompt(profession) {
  const sectionsList = SECTION_TEMPLATE.map(
    (s) => `${s.number}. ${s.heading}`
  ).join("\n");

  const system = `Ты — эксперт по охране труда в РФ. Твоя задача — составлять типовые инструкции
по охране труда для рабочих профессий на основе актуальных норм и общепринятой
практики. Пиши по-русски, официально-деловым стилем, без воды и без markdown-разметки
внутри текста пунктов. Отвечай СТРОГО валидным JSON без пояснений и без markdown-код-блоков.`;

  const user = `Составь инструкцию по охране труда для профессии: "${profession}".

Структура документа обязательна и не может быть изменена — используй ровно эти
5 разделов в этом порядке:
${sectionsList}

Формат ответа — JSON-объект со следующими полями:
{
  "title": "Инструкция по охране труда для ${profession}",
  "profession": "${profession}",
  "intro": "1-2 предложения общего введения об инструкции",
  "sections": [
    {
      "number": 1,
      "heading": "ОБЩИЕ ТРЕБОВАНИЯ ОХРАНЫ ТРУДА",
      "paragraphs": ["1.1. текст пункта...", "1.2. текст пункта...", "..."]
    }
  ]
}

Требования к содержанию:
- В разделе 1 — не менее 6 пунктов (допуск к работе, инструктажи, медосмотры,
  вредные/опасные факторы именно для этой профессии, СИЗ, дисциплина труда).
- В разделах 2, 3, 5 — не менее 4 пунктов в каждом, специфичных для профессии
  "${profession}" (реальное оборудование, материалы, риски этой профессии).
- В разделе 4 — не менее 4 пунктов о действиях при авариях, травмах, пожаре.
- Каждый пункт нумеруется по схеме "<номер раздела>.<номер пункта>." и
  содержит связный текст из 2-4 предложений.
- Не используй информацию, не имеющую отношения к охране труда данной профессии.
- Верни только JSON, без текста до или после него.`;

  return { system, user };
}

export const INSTRUCTION_SECTION_TEMPLATE = SECTION_TEMPLATE;
