import { execFile } from 'node:child_process';
import { randomUUID } from 'node:crypto';
import { lstat, mkdir, open, realpath, rename, rm } from 'node:fs/promises';
import path from 'node:path';
import { promisify } from 'node:util';

import { checkBackupArchiveInventory } from './backupArchiveInventory.js';
import { readBackupInventory } from './backupInventory.js';
import { backupManifest } from './backupManifest.js';
import { createBackup } from './backupService.js';
import { verifyBackupChecksum } from './restoreVerifier.js';

const execFileAsync = promisify(execFile);

function within(root, target) {
  const relative = path.relative(root, target);
  return !relative || (!relative.startsWith(`..${path.sep}`) && !path.isAbsolute(relative));
}

async function writeReport(reportPath, report, { initial = false } = {}) {
  const temporary = initial ? reportPath : `${reportPath}.${randomUUID()}.tmp`;
  let handle;
  try {
    handle = await open(temporary, 'wx', 0o600);
    await handle.writeFile(`${JSON.stringify(report, null, 2)}\n`, 'utf8');
    await handle.sync();
    await handle.close();
    handle = null;
    if (!initial) await rename(temporary, reportPath);
  } finally {
    await handle?.close();
    if (!initial) await rm(temporary, { force: true });
  }
}

export async function createVerifiedDataBackup({
  sourceRoot,
  outputDir,
  writersStopped = false,
  createArchive = createBackup,
} = {}) {
  if (writersStopped !== true)
    throw new Error('Stop all writers first and acknowledge this with --writers-stopped');
  if (
    typeof sourceRoot !== 'string' ||
    !sourceRoot.trim() ||
    typeof outputDir !== 'string' ||
    !outputDir.trim()
  )
    throw new TypeError('sourceRoot and a new outputDir are required');
  const supplied = path.resolve(sourceRoot);
  if (!(await lstat(supplied)).isDirectory())
    throw new Error('sourceRoot must be a real repository directory, not a symbolic link');
  const root = await realpath(supplied);
  const requested = path.resolve(outputDir);
  const parent = await realpath(path.dirname(requested));
  const output = path.join(parent, path.basename(requested));
  if (within(root, output)) throw new Error('Backup output must be outside the source repository');
  const reportPath = path.join(output, 'recovery.json');
  const restoredRoot = path.join(output, 'restored');
  await mkdir(output, { mode: 0o700 });
  const report = {
    schemaVersion: 1,
    status: 'incomplete',
    createdAt: new Date().toISOString(),
    manifestVersion: backupManifest.version,
    sourceRoot: root,
    outputDir: output,
    reportPath,
    restoredRoot,
    writersStoppedAcknowledged: true,
    sourceWritesPerformed: false,
    applicationStarted: false,
    limitations: [
      'Verifies business data only, not source code, environment secrets, Nginx, TLS or external services.',
      'The writers-stopped flag is an operator acknowledgement, not detection or suspension of running writers.',
      'Only the archive generated by this run is extracted, into this new isolated directory; no live restore is performed.',
      'Observed file membership, bytes and basic modes are compared; ownership, ACLs and extended attributes are not certified.',
    ],
  };
  await writeReport(reportPath, report, { initial: true });
  try {
    const result = await createArchive({ sourceRoot: root, outputDir: output });
    const { sourceInventory } = result;
    if (!sourceInventory?.entries || sourceInventory.sourceRoot !== root)
      throw new Error('Backup creator did not return the source inventory');
    report.archivePath = result.archivePath;
    report.checksumPath = result.checksumPath;
    report.checksum = result.checksum;
    if (!(await verifyBackupChecksum(result)))
      throw new Error('Backup checksum verification failed');
    await checkBackupArchiveInventory(result.archivePath, sourceInventory);
    await mkdir(restoredRoot, { mode: 0o700 });
    await execFileAsync('tar', ['-xzpf', result.archivePath, '-C', restoredRoot]);
    const restoredInventory = await readBackupInventory({ sourceRoot: restoredRoot });
    if (restoredInventory.fingerprint !== sourceInventory.fingerprint)
      throw new Error('Restored file bytes or inventory differ from the backup source');
    const current = await readBackupInventory({ sourceRoot: root });
    if (current.fingerprint !== sourceInventory.fingerprint)
      throw new Error(
        'Source changed during backup; keep writers stopped and repeat with a new output directory',
      );
    if (!(await verifyBackupChecksum(result)))
      throw new Error('Backup archive changed during verification');
    report.sourceInventory = sourceInventory;
    report.restoredFingerprint = restoredInventory.fingerprint;
    report.sourceAfterFingerprint = current.fingerprint;
    report.counts = {
      files: sourceInventory.entries.filter(entry => entry.kind === 'file').length,
      directories: sourceInventory.entries.filter(entry => entry.kind === 'directory').length,
      bytes: sourceInventory.entries.reduce((total, entry) => total + entry.size, 0),
    };
    report.archiveBytes = result.size;
    report.verifiedAt = new Date().toISOString();
    report.status = 'verified';
    await writeReport(reportPath, report);
    return report;
  } catch (error) {
    report.status = 'incomplete';
    report.error = error.message;
    await writeReport(reportPath, report).catch(() => {});
    throw error;
  }
}
